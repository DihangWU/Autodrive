def draw_label(world, x, y, bottom_z, text, lifetime, height=8.0):
    import carla
    cell = height / 7
    width = (6 * len(text) - 1) * cell
    # Four outward-facing panels, with enough spacing to avoid mirrored
    # front/back glyphs overlapping. Match the tower's two-tick lifetime.
    distance = width / 2 + cell
    color = carla.Color(255, 30, 180)
    for nx, ny in ((1, 0), (0, 1), (-1, 0), (0, -1)):
        # CARLA uses a left-handed XY frame: the camera's right points this
        # way when looking inward from the panel's outward normal.
        ux, uy = ny, -nx
        for index, char in enumerate(text):
            for row, bits in enumerate(_GLYPHS.get(char, _GLYPHS['?']).split('/')):
                for run in re.finditer('1+', bits):
                    left = (index * 6 + run.start()) * cell - width / 2
                    right = (index * 6 + run.end()) * cell - width / 2
                    z = bottom_z + (6.5 - row) * cell
                    a = carla.Location(x=x + nx * distance + ux * left,
                                       y=y + ny * distance + uy * left, z=z)
                    b = carla.Location(x=x + nx * distance + ux * right,
                                       y=y + ny * distance + uy * right, z=z)
                    world.debug.draw_line(a, b, thickness=cell * .65, color=color,
                                          life_time=lifetime, persistent_lines=True)
