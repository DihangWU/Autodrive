def label_text(identifier):
    """节点 ID 不变，只将显示文字 rsu0 转成 RSU 0。"""
    match = re.fullmatch(r'rsu_?(\d+)', identifier, re.IGNORECASE)
    return f'RSU {match.group(1)}' if match else identifier.upper().replace('_', ' ')


def draw_label(world, x, y, bottom_z, text, lifetime, height=DEFAULT_HEIGHT, elapsed=0.0):
    """只绘制一块竖直文字面板，以塔中心为轴水平旋转。"""
    import carla
    cell = height / 7
    width = (6 * len(text) - 1) * cell
    angle = math.tau * (elapsed % ROTATION_PERIOD) / ROTATION_PERIOD
    ux, uy = math.sin(angle), -math.cos(angle)
    color = carla.Color(*LABEL_COLOR)
    for index, char in enumerate(text):
        for row, bits in enumerate(_GLYPHS.get(char, _GLYPHS['?']).split('/')):
            for run in re.finditer('1+', bits):
                left = (index * 6 + run.start()) * cell - width / 2
                right = (index * 6 + run.end()) * cell - width / 2
                z = bottom_z + (6.5 - row) * cell
                a = carla.Location(x=x + ux * left, y=y + uy * left, z=z)
                b = carla.Location(x=x + ux * right, y=y + uy * right, z=z)
                world.debug.draw_line(a, b, thickness=cell * STROKE_WIDTH_RATIO, color=color,
                                      life_time=lifetime, persistent_lines=PERSISTENT_LINES)
